"""Optional ORS geocoding for station cities the offline gazetteer could not resolve.

Each unique unmatched ``(city, state)`` pair is queried **once** (structured Pelias
search, up to :data:`RESULTS_PER_QUERY` results, rate-limited) and the raw answers are
stored in a committed JSON cache (``data/ors_geocode_cache.json``). Later runs re-use the
cache and make zero calls.

A result is a *candidate* only if all of these hold:

1. its layer is locality-type (``locality`` or ``localadmin``),
2. it is in the USA,
3. its state equals the CSV state,
4. its coordinates fall inside that state's (padded) bounding box.

Two further rules guard against a *different* place of the same name (both found in
real data: Pelias's top answer for "Antioch, TN" is one of five Antiochs in Tennessee;
for "Henrico, VA" it is a hamlet ~100 miles from Henrico County):

5. **Ambiguity** — candidates whose name equals the CSV city are preferred; if the
   preferred candidates are more than :data:`AMBIGUITY_MILES` apart, the pair is
   rejected as ambiguous.
6. **County collision** — if the CSV "city" is also the name of a county in that state
   (people label stops "Henrico" meaning Henrico County), the chosen result must lie in
   that county.

Anything else is rejected with a logged reason and the city stays unmatched. Acceptance
is re-evaluated from the cache on every run, so changing a rule never needs new calls.
"""

import json
import logging
import time
from collections.abc import Callable, Collection, Iterable
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from apps.routing.exceptions import DomainError, RateLimitedError, RoutingNotConfiguredError
from apps.routing.services.geo import haversine_miles
from apps.routing.services.ors_client import GeocodeResult, ORSClient
from apps.stations.services.gazetteer import StateBounds
from apps.stations.services.normalize import compact_key, normalize_place_name

logger = logging.getLogger(__name__)

CACHE_VERSION = 2
RESULTS_PER_QUERY = 5
ACCEPTED_LAYERS: frozenset[str] = frozenset({"locality", "localadmin"})
AMBIGUITY_MILES = 25.0


@dataclass(frozen=True, slots=True)
class FallbackDecision:
    """Outcome of evaluating the cached ORS answers for one ``(city, state)`` pair."""

    city: str
    state: str
    accepted: bool
    reason: str  # "accepted" or why it was rejected
    result: GeocodeResult | None  # the accepted result, or the top result when rejected


def cache_key(city: str, state: str) -> str:
    """Stable cache key, e.g. ``"Ruther Glen|VA"``."""
    return f"{city}|{state}"


class FallbackCache:
    """JSON file mapping ``"City|ST"`` -> the structured-geocode features ORS returned."""

    def __init__(self, path: Path) -> None:
        self.path = path
        self.entries: dict[str, dict[str, Any]] = {}
        if path.exists():
            data = json.loads(path.read_text(encoding="utf-8"))
            if data.get("version") != CACHE_VERSION:
                raise ValueError(f"{path}: unsupported cache version {data.get('version')!r}")
            self.entries = data.get("entries", {})

    def __contains__(self, key: str) -> bool:
        return key in self.entries

    def __len__(self) -> int:
        return len(self.entries)

    def get(self, key: str) -> list[GeocodeResult]:
        """Cached results for ``key`` (possibly empty)."""
        return [GeocodeResult(**r) for r in self.entries[key]["results"]]

    def put(self, key: str, results: list[GeocodeResult]) -> None:
        self.entries[key] = {
            "queried_at": datetime.now(UTC).isoformat(timespec="seconds"),
            "results": [asdict(r) for r in results],
        }

    def save(self) -> None:
        """Write the cache (sorted, pretty-printed, so diffs stay reviewable)."""
        self.path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "version": CACHE_VERSION,
            "description": (
                "ORS structured-geocode answers for station cities missing from the Census "
                "gazetteer. Generated by `manage.py geocode_stations --ors-fallback`."
            ),
            "entries": dict(sorted(self.entries.items())),
        }
        self.path.write_text(json.dumps(payload, indent=1, ensure_ascii=False) + "\n", "utf-8")


def _basic_rejection(result: GeocodeResult, state: str, bounds: dict[str, StateBounds]) -> str:
    """Reason a result fails rules 1-4, or ``""`` if it is a candidate."""
    if result.layer not in ACCEPTED_LAYERS:
        return f"layer '{result.layer}' is not locality-type"
    if result.country_a != "USA":
        return f"country '{result.country_a}' is not USA"
    if result.region_a != state:
        return f"state '{result.region_a}' != CSV state '{state}'"
    state_bounds = bounds.get(state)
    if state_bounds is None or not state_bounds.contains(result.lat, result.lon):
        return f"({result.lat:.4f}, {result.lon:.4f}) outside {state} bounding box"
    return ""


def _same_name(a: str, b: str) -> bool:
    return compact_key(normalize_place_name(a)) == compact_key(normalize_place_name(b))


def _county_base(county: str) -> str:
    for suffix in (" County", " Parish", " Borough", " Census Area"):
        county = county.removesuffix(suffix)
    return normalize_place_name(county)


def evaluate(
    city: str,
    state: str,
    results: list[GeocodeResult],
    bounds: dict[str, StateBounds],
    counties: Collection[tuple[str, str]] = frozenset(),
) -> FallbackDecision:
    """Apply rules 1-6 (see module docstring) to the cached answers for one pair."""
    top = results[0] if results else None

    def reject(reason: str, result: GeocodeResult | None = top) -> FallbackDecision:
        return FallbackDecision(city, state, False, reason, result)

    if not results:
        return reject("no result")

    candidates = [r for r in results if not _basic_rejection(r, state, bounds)]
    if not candidates:
        return reject(_basic_rejection(results[0], state, bounds))

    exact = [r for r in candidates if _same_name(r.name, city)]
    pool = exact or candidates
    chosen = pool[0]
    spread = max(float(haversine_miles(chosen.lat, chosen.lon, r.lat, r.lon)) for r in pool)
    if spread > AMBIGUITY_MILES:
        return reject(
            f"ambiguous: {len(pool)} localities named like '{city}' in {state} "
            f"up to {spread:.0f} mi apart",
            chosen,
        )

    city_key = normalize_place_name(city)
    if (state, city_key) in counties and _county_base(chosen.county) != city_key:
        return reject(
            f"'{city}' is also a county in {state}, but the result is in "
            f"'{chosen.county or 'unknown county'}'",
            chosen,
        )
    return FallbackDecision(city, state, True, "accepted", chosen)


def fetch_missing(
    pairs: Iterable[tuple[str, str]],
    cache: FallbackCache,
    client: ORSClient,
    min_interval_seconds: float,
    sleep: Callable[[float], None] = time.sleep,
) -> int:
    """Query ORS for pairs not yet cached, saving after each answer. Returns calls made.

    Transient provider errors skip the pair (it is retried on the next run); a quota
    error (429) or missing key stops the batch, keeping the progress made so far.
    """
    calls = 0
    last_call = float("-inf")
    for city, state in pairs:
        key = cache_key(city, state)
        if key in cache:
            continue
        wait = min_interval_seconds - (time.monotonic() - last_call)
        if wait > 0:
            sleep(wait)
        last_call = time.monotonic()
        calls += 1
        try:
            results = client.geocode_structured(city, state, size=RESULTS_PER_QUERY)
        except (RateLimitedError, RoutingNotConfiguredError):
            cache.save()
            raise
        except DomainError as exc:
            logger.warning(
                "ORS fallback for %s failed (%s %s); will retry next run", key, exc, exc.details
            )
            continue
        cache.put(key, results)
        cache.save()
    return calls


def decide_all(
    pairs: Iterable[tuple[str, str]],
    cache: FallbackCache,
    bounds: dict[str, StateBounds],
    counties: Collection[tuple[str, str]] = frozenset(),
) -> list[FallbackDecision]:
    """Evaluate every pair that has a cached answer; log each rejection with its reason."""
    decisions = []
    for city, state in pairs:
        key = cache_key(city, state)
        if key not in cache:
            continue
        decision = evaluate(city, state, cache.get(key), bounds, counties)
        if not decision.accepted:
            label = decision.result.label if decision.result else "-"
            logger.info("ORS fallback rejected %s -> %s: %s", key, label, decision.reason)
        decisions.append(decision)
    return decisions
